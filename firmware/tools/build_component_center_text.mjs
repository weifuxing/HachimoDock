/* Run with node from the firmware tree. Uses the desktop Canvas text renderer. */
import fs from "node:fs";
import { execFileSync } from "node:child_process";
import path from "node:path";
import { deflateSync, inflateSync } from "node:zlib";
import { fileURLToPath, pathToFileURL } from "node:url";
import { chromium } from "../../pc/node_modules/playwright/index.mjs";
import { CENTER_CARD_TITLE } from "../../pc/src/lib/component-center-text.js";

const firmware = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const pc = path.resolve(firmware, "../pc");
const asset = path.join(firmware, "assets/component-center");
const labels = new Map();
function add(text, px, width, weight = 500) {
  labels.set(`${px}:${text}`, { text, px, width, weight });
}
add("组件中心", 32, 300, 700);
for (const text of ["全部", "小游戏", "小工具", "影音"]) add(text, 20, 130, 700);
for (const text of ["正在准备组件，可返回取消", "轻点打开 · 左右滑动翻页",
  "在 PC 组件中心添加后，即可在这里打开", "切换筛选查看其他组件",
  "摇杆选择 · 确认打开 · 长按摇杆切类 · 全局键返回"]) add(text, 18, 580);
for (const text of ["开始一场小游戏", "随时打开体验", "连接电脑使用", "打开体验",
  "实时行情", "音乐与歌词", "记录与管理", "电脑实时状态"]) add(text, 18, 226);
add("已打开", 16, 64, 700);
add("还没有组件", 27, 536, 700);
add("此类暂无组件", 27, 536, 700);
for (const text of ["已安装", "此类", "个", ..."0123456789"]) add(text, 16, 130);
const factory = JSON.parse(fs.readFileSync(path.join(firmware, "factory-config.json"))).components;
const firmwareOnly = new Set(factory.firmwareOnlyIds || []);
for (const group of ["builtin-clawpkgs", "optional-clawpkgs"]) {
  const directory = path.join(pc, group);
  if (!fs.existsSync(directory)) continue;
  const entries = fs.readdirSync(directory).filter(entry => !firmwareOnly.has(entry));
  if (group === "builtin-clawpkgs") entries.push(...firmwareOnly);
  for (const entry of entries.sort()) {
    const base = firmwareOnly.has(entry) ? path.resolve(firmware, factory.firmwareOnlyPackagesDir) : directory;
    const widget = path.join(base, entry, "runtime/widget.json");
    if (!fs.existsSync(widget)) continue;
    const title = JSON.parse(fs.readFileSync(widget, "utf8")).dashboard?.title || entry;
    add(title, CENTER_CARD_TITLE.px, CENTER_CARD_TITLE.width, CENTER_CARD_TITLE.weight);
  }
}

const browser = await chromium.launch({ args: ["--allow-file-access-from-files"] });
try {
  const page = await browser.newPage();
  await page.goto(pathToFileURL(path.join(pc, "package.json")).href);
  const rows = await page.evaluate(async ([url, fontUrl, specs]) => {
    const { ensureBubbleFont } = await import(fontUrl);
    await ensureBubbleFont();
    const { renderCenterText } = await import(url);
    return specs.map(({ text, ...spec }) => [...renderCenterText(text, spec)]);
  }, [
    pathToFileURL(path.join(pc, "src/lib/component-center-text.js")).href,
    pathToFileURL(path.join(pc, "src/lib/bubble-font.js")).href,
    [...labels.values()],
  ]);
  const lines = ["/* Generated by build_component_center_text.mjs. */",
    "static const uint8_t center_text_data_z[] = {"];
  const index = [];
  let offset = 0;
  for (const [i, { text, px }] of [...labels.values()].entries()) {
    const data = rows[i];
    index.push(`  {${JSON.stringify(text)}, ${px}, ${offset}, ${data.length}},`);
    offset += data.length;

  }
  const raw = Buffer.concat(rows.map(row => Buffer.from(row)));
  const encoded = process.argv.includes("--zopfli")
    ? execFileSync(process.env.PET_FONT_PACK_PYTHON || "python3", ["-c",
      "import sys; from zopfli.zlib import compress; sys.stdout.buffer.write(compress(sys.stdin.buffer.read(), numiterations=15))"], {input: raw})
    : deflateSync(raw, {level: 9});
  if (!inflateSync(encoded).equals(raw)) throw new Error("Component center font masks failed exact round-trip");
  for (let j = 0; j < encoded.length; j += 24) {
    lines.push(`  ${Array.from(encoded.subarray(j, j + 24)).join(",")},`);
  }
  lines.push("};", `enum { PET_CENTER_LABEL_BYTES = ${offset} };`, "static const struct { const char *text; uint8_t px; uint32_t offset; uint16_t length; } center_text_index[] = {", ...index, "};", "");
  fs.writeFileSync(path.join(asset, "text_masks.h"), lines.join("\n"));
  console.log(`${rows.length} masks, ${offset} bytes, ${encoded.length} compressed`);
} finally {
  await browser.close();
}
