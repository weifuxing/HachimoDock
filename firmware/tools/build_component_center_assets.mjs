// Deterministic device encoding, not UI screenshots: shared package art + native controls.
import {readFileSync,writeFileSync,mkdirSync,existsSync} from 'node:fs';
import {resolve,dirname,join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
import {deflateSync,inflateSync} from 'node:zlib';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'../..');
const out=join(root,'firmware/assets/component-center');
mkdirSync(out,{recursive:true});
const components=JSON.parse(readFileSync(join(root,'firmware/factory-config.json'))).components;
const records=[], frames=[];
for(const id of components.ids){
  const directory=components.firmwareOnlyIds?.includes(id)?components.firmwareOnlyPackagesDir:components.packagesDir;
  const pkg=resolve(root,'firmware',directory,id);
  const widget=JSON.parse(readFileSync(join(pkg,'runtime/widget.json')));
  const manifest=JSON.parse(readFileSync(join(pkg,'component.json')));
  const image=widget.surface?.images?.find(i=>i.encoding==='jpeg')||widget.surface?.images?.[0];
  const cover=join(pkg,'pc/cover.png');
  const source=existsSync(cover)?cover:image&&join(pkg,image.asset);
  const hasArt=Boolean(source&&existsSync(source));
  const frameBytes=16*2+64*48/2;
  const rgb=hasArt?execFileSync('ffmpeg',['-v','error','-i',source,'-vf','scale=64:48:flags=lanczos','-frames:v','1','-f','rawvideo','-pix_fmt','rgb24','pipe:1']):null;
  const packed=rgb?execFileSync(process.env.CENTER_THUMB_PYTHON||'python3',
    [join(dirname(fileURLToPath(import.meta.url)),'pack_center_thumbnail.py')],{input:rgb}):Buffer.alloc(frameBytes);
  if(packed.length!==frameBytes)throw Error('Unexpected thumbnail dimensions');
  frames.push(packed);
  const caption=widget.host||widget.data||widget.media?'连接电脑使用':manifest.kind==='game'?'开始一场小游戏':'随时打开体验';
  records.push(`  {${JSON.stringify(id)}, ${JSON.stringify(caption)}, ${hasArt?'true':'false'}},`);
}
execFileSync('ffmpeg',['-v','error','-y','-i',join(out,'background.png'),'-frames:v','1','-q:v','7','-pix_fmt','yuvj420p',join(out,'center_background.jpg')]);
const raw=Buffer.concat(frames);
const packed=process.argv.includes('--zopfli')
  ? execFileSync(process.env.CENTER_THUMB_PYTHON||'python3',
      ['-c','import sys; from zopfli.zlib import compress; sys.stdout.buffer.write(compress(sys.stdin.buffer.read(), numiterations=15))'],
      {input:raw})
  : deflateSync(raw,{level:9});
if(!inflateSync(packed).equals(raw))throw Error('Launcher thumbnails failed exact round-trip');
writeFileSync(join(out,'center_thumbs.deflate'),packed);
writeFileSync(join(out,'catalog.h'),`/* Generated by build_component_center_assets.mjs; source art stays in component packages. */\nstatic const struct { const char *id, *caption; bool art; } center_art_catalog[] = {\n${records.join('\n')}\n};\n#define CENTER_ART_COUNT (sizeof(center_art_catalog)/sizeof(center_art_catalog[0]))\n`);
const bytes=packed.length+readFileSync(join(out,'center_background.jpg')).length;
if(bytes>128*1024)throw Error('Launcher artwork exceeds 128 KiB');
console.log(`${components.ids.length} entries; launcher artwork ${bytes} bytes`);
